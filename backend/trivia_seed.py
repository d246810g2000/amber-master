from database import SessionLocal
import models
from sqlalchemy import update

def seed_trivia_questions():
    db = SessionLocal()
    try:
        updated_count = 0
        added_count = 0
        for q in TRIVIA_QUESTIONS:
            chapter, chapter_name, q_code, question, opt_a, opt_b, opt_c, opt_d, ans_idx, explanation = q
            
            existing = db.query(models.TriviaQuestion).filter(models.TriviaQuestion.question_code == q_code).first()
            if existing:
                # Update options and answer index
                existing.option_a = opt_a
                existing.option_b = opt_b
                existing.option_c = opt_c
                existing.option_d = opt_d
                existing.answer_index = ans_idx
                existing.explanation = explanation
                existing.question = question
                updated_count += 1
            else:
                db_q = models.TriviaQuestion(
                    chapter=chapter,
                    chapter_name=chapter_name,
                    question_code=q_code,
                    question=question,
                    option_a=opt_a,
                    option_b=opt_b,
                    option_c=opt_c,
                    option_d=opt_d,
                    answer_index=ans_idx,
                    explanation=explanation
                )
                db.add(db_q)
                added_count += 1
        db.commit()
        print(f"Trivia questions successfully updated! Added: {added_count}, Updated: {updated_count}")
    except Exception as e:
        db.rollback()
        print(f"Error updating trivia questions: {e}")
    finally:
        db.close()

if __name__ == "__main__":
    seed_trivia_questions()
